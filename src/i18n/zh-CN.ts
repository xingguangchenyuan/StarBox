type Dict = Record<string, unknown>;

const flatten = (obj: Dict, prefix = "", out: Record<string, string> = {}): Record<string, string> => {
  for (const [k, v] of Object.entries(obj)) {
    const key = prefix ? `${prefix}.${k}` : k;
    if (v && typeof v === "object") flatten(v as Dict, key, out);
    else out[key] = String(v);
  }
  return out;
};

const dicts: Record<string, Record<string, string>> = {
  "zh-CN": flatten(zhCN as unknown as Dict),
};

let locale = "zh-CN";

export function setLocale(next: string) {
  locale = dicts[next] ? next : "zh-CN";
}

export function getLocale(): string {
  return locale;
}

/** t("hero.play") / t("hero.running", { time: "1 小时 12 分" }) */
export function t(key: string, params?: Record<string, string | number>): string {
  const dict = dicts[locale] ?? dicts["zh-CN"];
  let s = dict[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}
